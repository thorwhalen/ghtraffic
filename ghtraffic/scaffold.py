"""Setting up a data repository: the workflow and the config it runs with.

``ghtraffic init <dir>`` writes two files into a (preferably **private**) git
repository: ``ghtraffic.toml`` (which owners to collect) and
``.github/workflows/ghtraffic.yml`` (a twice-weekly scheduled run of this repo's
composite action, which commits the merged history back). Nothing else is
needed in that repo; the first run is the cold start.
"""

from __future__ import annotations

import os
from collections.abc import Iterable
from pathlib import Path

DFLT_ACTION_REF = "thorwhalen/ghtraffic@main"
#: 03:17 UTC on Mondays and Thursdays: off the top of the hour (GitHub delays
#: on-the-hour crons). Every day is seen 3-4 times within its 14-day window,
#: so two missed runs in a row still lose nothing, for ~9 runs a month.
DFLT_CRON = "17 3 * * 1,4"
WORKFLOW_PATH = ".github/workflows/ghtraffic.yml"

WORKFLOW_TEMPLATE = """\
# Collects GitHub traffic into this repository, twice a week.
# Generated by `ghtraffic init`. Docs: https://github.com/thorwhalen/ghtraffic
#
# Needs one secret, GHTRAFFIC_TOKEN: a token with push access to the repos to
# collect (a classic token with the `repo` and `read:org` scopes covers every
# owner you can push to). Keep this repository PRIVATE if any collected repo is.
name: ghtraffic
on:
  schedule:
    - cron: "{cron}"
  workflow_dispatch:
permissions:
  contents: write
concurrency:
  group: ghtraffic
  cancel-in-progress: false
jobs:
  collect:
    runs-on: ubuntu-latest
    timeout-minutes: 15
    steps:
      - uses: actions/checkout@v4
      - uses: {action_ref}
        with:
          token: ${{{{ secrets.GHTRAFFIC_TOKEN }}}}
"""

CONFIG_TEMPLATE = """\
# ghtraffic settings. Every key is optional; see
# https://github.com/thorwhalen/ghtraffic#configuration
[ghtraffic]
# User and organization logins. "@me" = the token's user and all their orgs.
owners = [{owners}]
# owner/repo glob patterns to skip, e.g. "someorg/*" or "me/secret-*".
exclude = []
include_forks = true
include_archived = true
# Days between snapshots of the 14-day aggregates (referrers, paths, totals).
# 14 tiles the window: snapshots never overlap, so their counts add up.
snapshot_every_days = 14
# Rebuild each repo's star history from stargazer dates the first time it is seen.
backfill_stars = true
"""

GITIGNORE = "__pycache__/\n"


def render_workflow(*, cron: str = DFLT_CRON, action_ref: str = DFLT_ACTION_REF) -> str:
    """The workflow YAML for a data repo."""
    return WORKFLOW_TEMPLATE.format(cron=cron, action_ref=action_ref)


def render_config(owners: Iterable[str] = ("@me",)) -> str:
    """The ``ghtraffic.toml`` text for the given owners."""
    return CONFIG_TEMPLATE.format(owners=", ".join(f'"{o}"' for o in owners))


def init_data_repo(
    rootdir: str | os.PathLike,
    *,
    owners: Iterable[str] = ("@me",),
    cron: str = DFLT_CRON,
    action_ref: str = DFLT_ACTION_REF,
    overwrite: bool = False,
) -> list[str]:
    """Write the workflow and config into ``rootdir``; return the paths written."""
    root = Path(rootdir).expanduser()
    files = {
        WORKFLOW_PATH: render_workflow(cron=cron, action_ref=action_ref),
        "ghtraffic.toml": render_config(owners),
        ".gitignore": GITIGNORE,
    }
    written = []
    for rel, text in files.items():
        p = root / rel
        if p.exists() and not overwrite:
            continue
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text, encoding="utf-8")
        written.append(rel)
    return written
